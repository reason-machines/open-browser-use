#!/usr/bin/env node
// Emit the injected page runtime as a standalone file (dist/injected/bundle.js)
// for inspection, size tracking and non-TS consumers. The daemon itself uses
// INJECTED_BUNDLE_SOURCE from dist/injected/index.js (same content).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { INJECTED_BUNDLE_SOURCE, INJECTED_VERSION } = await import(join(root, "dist/injected/index.js"));
// Sanity: the bundle must parse as a standalone script.
new Function(INJECTED_BUNDLE_SOURCE);
const out = join(root, "dist/injected/bundle.js");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// obu injected runtime v${INJECTED_VERSION} (generated by scripts/build-injected.mjs)\n${INJECTED_BUNDLE_SOURCE}\n`);
console.log(`obu injected bundle v${INJECTED_VERSION}: ${INJECTED_BUNDLE_SOURCE.length} bytes -> dist/injected/bundle.js`);
